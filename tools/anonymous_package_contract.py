"""The anonymous-package contract, pinned in code rather than in shipped data.

The submission supplement contains two files that are anonymized copies of the
study's evidence: one metadata string is replaced so that double-blind review is
not defeated by a version-control identifier.  `ANONYMIZATION.json` ships with
the supplement so a reviewer is told what changed.

`ANONYMIZATION.json` is a reviewer-visible, reviewer-editable file, so it is a
*claim*, never an authority.  An earlier version of the shipped verifiers
compared each packaged file against the digest recorded in that declaration.
That let anyone edit a packaged file, recompute its `.sha256` sidecar, update the
declaration's `packaged_sha256`, and pass every check -- which is exactly the
mutation an independent reviewer demonstrated with `candidate_count`.

This module is the fix.  It pins, in code:

* the exact set of packaged paths -- no more, no fewer;
* the exact field name and replacement token;
* the exact content SHA-256 and byte count of the original evidence;
* the exact content SHA-256 and byte count of the sanitized bytes;
* the exact sidecar text that must sit next to each sanitized file;
* the exact declaration schema and record set.

Everything the shipped verifiers accept is measured against these constants.
`ANONYMIZATION.json` is then *validated against them*: it must agree exactly, and
disagreement is a failure of the declaration, not a new expectation.

Nothing here is a Git revision or an author-linked identifier.  Every hex string
below is a SHA-256 content digest of a file, which is what a reviewer needs in
order to check bytes, and which says nothing about who produced them.  The
removed value itself is deliberately absent from this file and from every other
shipped byte; it is recorded only in the internal release metadata.

The constants are generated by, and cross-checked against, the packaging step:
`submissions/tmlr_2026/package.py` refuses to build if the bytes it produces do
not match them, and a test asserts the same in the other direction, so the
contract cannot silently drift away from what is actually shipped.

Two modes, and the difference matters:

* **Optional repository mode** (the default).  A tree with no declaration is not
  a package, so there is no anonymization contract to check.  This is right for
  running the checker directly against the original committed evidence, and it
  is why repository tooling does not have to carry an anonymization file.
* **Required package mode** (`--require-package`, or the environment variable
  `CCE_REQUIRE_ANONYMOUS_PACKAGE=1`).  The tree *must* be an anonymous package:
  a missing declaration is a failure, not a pass.  Without this the omission of
  `ANONYMIZATION.json` silently downgrades a supplement to repository semantics,
  and a supplement carrying the original, author-linked evidence verifies clean.
  The shipped supplement entry point always runs in this mode, first, and stops
  there if it fails.
"""

