def sidecar_text(relative: str) -> str:
    """The exact bytes the `.sha256` next to a sanitized file must contain."""

    return f"{CONTRACT[relative]['packaged_sha256']}  {Path(relative).name}\n"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def is_packaged_tree(root: Path) -> bool:
    """True when `root` is an anonymous supplement rather than the repository."""

    return (root / DECLARATION_NAME).is_file()


def package_required(explicit: bool | None = None) -> bool:
    """Resolve the package-required signal: explicit flag first, then the env.

    This is an explicit contract, never a guess about the tree.  A checker must
    be told that it is looking at a package; it must not infer it from paths,
    because the whole point is that a tampered package may be missing exactly
    the file such an inference would key on.
    """

    if explicit is not None:
        return bool(explicit)
    return os.environ.get(ENV_REQUIRE_PACKAGE, "").strip().lower() in {
        "1", "true", "yes", "on",
    }


def missing_declaration_result(root: Path) -> tuple[str, bool, str]:
    """The failure emitted when package mode is required but nothing declares it."""

    return (
        f"{DECLARATION_NAME} is present (required package mode)",
        False,
        f"no {DECLARATION_NAME} at {root}. Package mode was required, so this "
        "tree cannot be treated as the repository: an anonymous supplement that "
        "has lost its declaration is either incomplete or has been reverted to "
        "the original, author-linked evidence, and both must fail rather than "
        "silently fall back to repository semantics.",
    )


def original_sha256(relative: str) -> str | None:
    """The pinned digest of the original evidence behind a sanitized path."""

    record = CONTRACT.get(str(relative))
    return str(record["original_sha256"]) if record else None


def load_followup_contract(root: Path):
    """Load the exact-root helper only after its independent digest matches."""
    import importlib.util

    relative = "tools/followup_anonymous_contract.py"
    path = root / relative
    if (not path.is_file() or path.is_symlink()
            or sha256_file(path) != SHIPPED_TOOL_DIGESTS.get(relative)):
        raise ImportError("follow-up contract module is missing or differs from its independent pin")
    spec = importlib.util.spec_from_file_location("packaged_followup_contract", path)
    if spec is None or spec.loader is None:
        raise ImportError("Cannot load the pinned follow-up contract module")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def check_shipped_tools(root: Path) -> list[tuple[str, bool, str]]:
    """Verify the shipped tools whose bytes decide a verification result.

    Runs in both modes: the repository copy and the packaged copy are the same
    bytes, so both are held to the same pins.  A tool that is absent from this
    tree is not a failure -- `source.zip` carries none of them -- but a tool
    that is present and does not match is.
    """

    results: list[tuple[str, bool, str]] = []
    for relative, pinned in sorted(SHIPPED_TOOL_DIGESTS.items()):
        path = root / relative
        if not path.is_file():
            continue
        actual = sha256_file(path)
        results.append((
            f"shipped tool matches the pinned contract: {relative}",
            actual == pinned,
            f"sha256 {actual} vs pinned {pinned}. This file is generated data "
            "that the ledger reads; editing a source and its pin together must "
            "not authorize itself, so the pin is held here as well.",
        ))
    return results


def check_provenance(root: Path) -> list[tuple[str, bool, str]]:
    """Verify the shipped provenance records against their pinned constants.

    Runs in both modes: these bytes are the same in the repository and in a
    package, because the anonymizing transform does not touch them.
    """

    results: list[tuple[str, bool, str]] = []
    for relative, pinned in sorted(PROVENANCE_PINS.items()):
        path = root / relative
        if not path.is_file():
            results.append((f"provenance record present: {relative}", False,
                            "missing"))
            continue
        actual = sha256_file(path)
        size = path.stat().st_size
        results.append((
            f"provenance bytes match the pinned contract: {relative}",
            actual == pinned["sha256"] and size == pinned["bytes"],
            f"sha256 {actual} vs pinned {pinned['sha256']}; "
            f"{size} bytes vs pinned {pinned['bytes']}",
        ))
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            results.append((f"provenance parses: {relative}", False,
                            repr(error)))
            continue
        problems = []
        if record.get("artifact") != pinned["describes"]:
            problems.append(f"artifact={record.get('artifact')!r}")
        if record.get("artifact_sha256") != pinned["artifact_sha256"]:
            problems.append(
                f"artifact_sha256={record.get('artifact_sha256')!r}")
        if record.get("input_set_sha256") != pinned["input_set_sha256"]:
            problems.append(
                f"input_set_sha256={record.get('input_set_sha256')!r}")
        if record.get("schema_version") != pinned["schema_version"]:
            problems.append(f"schema_version={record.get('schema_version')!r}")
        inputs = record.get("inputs")
        if not isinstance(inputs, list) or len(inputs) != pinned["input_count"]:
            problems.append(
                f"inputs={len(inputs) if isinstance(inputs, list) else inputs} "
                f"vs pinned {pinned['input_count']}")
        elif not all(isinstance(item, dict) and item.get("path")
                     and isinstance(item.get("sha256"), str)
                     and len(item["sha256"]) == 64 for item in inputs):
            problems.append("an input entry has no path or no 64-hex digest")
        results.append((
            f"provenance still binds its artifact: {relative}",
            not problems,
            "; ".join(problems),
        ))
    return results


def check(root: Path, *, require_package: bool | None = None
          ) -> list[tuple[str, bool, str]]:
    """Validate a packaged tree against the pinned contract.

    Returns `(name, ok, detail)` triples.  The caller decides how to report
    them; every `ok=False` is a hard failure.

    With package mode required, a tree without a declaration yields a single
    failing result rather than an empty pass.
    """

    results: list[tuple[str, bool, str]] = []

    def record_result(name: str, ok: bool, detail: str = "") -> None:
        results.append((name, ok, detail))

    # The provenance pins hold in both modes: the transform does not touch
    # those bytes, so a repository check and a package check expect the same
    # ones.  They run before the declaration so that a tree with no declaration
    # is still held to them.
    results.extend(check_provenance(root))
    results.extend(check_shipped_tools(root))

    if not is_packaged_tree(root):
        if package_required(require_package):
            results.append(missing_declaration_result(root))
        return results

    # The follow-up has a separate typed metadata contract; retaining the older
    # declaration cannot downgrade a supplement to the historical evidence set.
    # Its code and all packaged bytes are pinned independently of both editable
    # declarations. The old single-field contract below remains unchanged.
    try:
        followup_problems = load_followup_contract(root).validate_packaged(root)
    except (ImportError, OSError, ValueError, KeyError, TypeError) as error:
        followup_problems = [repr(error)]
    record_result("follow-up compact evidence matches its typed anonymous contract",
                  not followup_problems, "; ".join(followup_problems))

    declaration_path = root / DECLARATION_NAME
    try:
        declaration = json.loads(declaration_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        record_result(f"{DECLARATION_NAME} parses", False, repr(error))
        return results

    # ---- the declaration must have the shape we pinned --------------------
    # Exact equality, not containment.  A declaration carrying extra top-level
    # keys is not the document this contract describes: the extra key may say
    # something a reviewer will read and act on, and nothing here has checked
    # it.  Missing and unexpected keys are both reported so the failure names
    # what is actually wrong.
    declared_keys = set(declaration)
    missing_keys = REQUIRED_DECLARATION_KEYS - declared_keys
    unexpected_keys = declared_keys - REQUIRED_DECLARATION_KEYS
    record_result(
        f"{DECLARATION_NAME} has exactly the pinned top-level schema",
        not missing_keys and not unexpected_keys
        and declaration.get("schema_version") == DECLARATION_SCHEMA_VERSION,
        f"missing {sorted(missing_keys)}; unexpected {sorted(unexpected_keys)}; "
        f"schema_version={declaration.get('schema_version')!r}",
    )

    transformed = declaration.get("transformed")
    if not isinstance(transformed, list):
        record_result(f"{DECLARATION_NAME} lists transformed records", False,
                      f"got {type(transformed).__name__}")
        return results

    declared_paths = [record.get("path") for record in transformed]
    record_result(
        "declared record set is exactly the pinned set",
        sorted(p for p in declared_paths if isinstance(p, str)) == sorted(CONTRACT)
        and len(declared_paths) == len(CONTRACT),
        f"declared {sorted(str(p) for p in declared_paths)}; "
        f"pinned {sorted(CONTRACT)}",
    )

    by_path = {
        record.get("path"): record
        for record in transformed
        if isinstance(record, dict)
    }

    # ---- each pinned path, checked against code and not against the file --
    for relative, pinned in sorted(CONTRACT.items()):
        path = root / relative
        if not path.is_file():
            record_result(f"sanitized file present: {relative}", False, "missing")
            continue

        actual_bytes = path.stat().st_size
        actual_sha = sha256_file(path)
        record_result(
            f"sanitized bytes match the pinned contract: {relative}",
            actual_sha == pinned["packaged_sha256"]
            and actual_bytes == pinned["packaged_bytes"],
            f"sha256 {actual_sha} vs pinned {pinned['packaged_sha256']}; "
            f"{actual_bytes} bytes vs pinned {pinned['packaged_bytes']}",
        )

        # the redacted field must hold exactly the pinned placeholder
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
            field_value = loaded.get(PACKAGED_FIELD)
        except (OSError, ValueError) as error:
            field_value = f"<unreadable: {error!r}>"
        record_result(
            f"redacted field holds the pinned token: {relative}",
            field_value == REPLACEMENT_TOKEN,
            f"{PACKAGED_FIELD}={field_value!r}, pinned {REPLACEMENT_TOKEN!r}",
        )

        # the sidecar must be exactly the pinned text, not merely self-consistent
        sidecar = Path(f"{path}.sha256")
        try:
            sidecar_actual = sidecar.read_text(encoding="ascii")
        except OSError:
            sidecar_actual = ""
        record_result(
            f"sidecar text matches the pinned contract: {relative}.sha256",
            sidecar_actual == sidecar_text(relative),
            f"sidecar {sidecar_actual!r}, pinned {sidecar_text(relative)!r}",
        )

        # and the declaration must agree with the pinned values, not define them
        declared = by_path.get(relative)
        if declared is None:
            record_result(f"declaration covers {relative}", False, "no record")
            continue
        field_problems = []
        if set(declared) - REQUIRED_RECORD_FIELDS:
            field_problems.append(
                f"unexpected fields {sorted(set(declared) - REQUIRED_RECORD_FIELDS)}")
        if REQUIRED_RECORD_FIELDS - set(declared):
            field_problems.append(
                f"missing fields {sorted(REQUIRED_RECORD_FIELDS - set(declared))}")
        if set(declared) & FORBIDDEN_RECORD_FIELDS:
            field_problems.append(
                f"internal-only fields leaked "
                f"{sorted(set(declared) & FORBIDDEN_RECORD_FIELDS)}")
        for key in ("original_sha256", "packaged_sha256",
                    "original_bytes", "packaged_bytes"):
            if declared.get(key) != pinned[key]:
                field_problems.append(
                    f"{key}={declared.get(key)!r} but pinned {pinned[key]!r}")
        if declared.get("field") != PACKAGED_FIELD:
            field_problems.append(f"field={declared.get('field')!r}")
        if declared.get("replacement") != REPLACEMENT_TOKEN:
            field_problems.append(f"replacement={declared.get('replacement')!r}")
        record_result(
            f"declaration agrees with the pinned contract: {relative}",
            not field_problems,
            "; ".join(field_problems),
        )

    return results


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument(
        "--require-package", action="store_true", default=None,
        help="fail if the tree is not an anonymous package. The shipped "
             "supplement entry point always passes this; it is also implied by "
             f"{ENV_REQUIRE_PACKAGE}=1.")
    parser.add_argument(
        "--list-pinned", action="store_true",
        help="print the paths this contract verifies from pinned constants, "
             "one per line, and exit. The supplement's sidecar sweep uses it "
             "so that a file covered here is not reported as uncovered there.")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    required = package_required(args.require_package)

    if args.list_pinned:
        try:
            followup = load_followup_contract(root)
        except (ImportError, OSError, ValueError, KeyError, TypeError) as error:
            print(f"FAIL: {error}")
            return 1
        for relative in sorted(set(CONTRACT) | set(PROVENANCE_PINS)):
            print(relative)
            print(f"{relative}.sha256")
        for relative in sorted(set(followup.INPUT_PATHS) | set(followup.ARTIFACT_PINS)
                               | set(followup.SCHEMATIC_PINS)):
            print(relative)
        print(followup.DECLARATION_NAME)
        return 0

    if not is_packaged_tree(root) and not required:
        # Repository mode has nothing to say about the declaration, but the
        # provenance pins hold here too and used to go unchecked entirely.
        print(f"no {DECLARATION_NAME} at {root}: this is not an anonymous "
              "package, so there is no anonymization contract to check "
              "(optional repository mode)")
        # The provenance pins and the shipped-tool pins both hold here: neither
        # depends on the anonymizing transform, and the repository copy of a
        # shipped tool is the same bytes the supplement carries.
        results = check_provenance(root) + check_shipped_tools(root)
        bad = sum(1 for _, ok, _ in results if not ok)
        for name, ok, detail in results:
            print(f"{'PASS' if ok else 'FAIL'}  {name}")
            if not ok:
                print(f"        -> {detail}")
        print()
        print(f"{len(results) - bad} of {len(results)} pinned provenance and "
              "shipped-tool checks passed")
        return 1 if bad else 0

    print(f"mode: {'REQUIRED anonymous package' if required else 'optional'}")
    results = check(root, require_package=required)
    bad = 0
    for name, ok, detail in results:
        print(f"{'PASS' if ok else 'FAIL'}  {name}")
        if not ok:
            print(f"        -> {detail}")
            bad += 1
    print()
    print(f"{len(results) - bad} of {len(results)} anonymous-package contract "
          "checks passed, against constants pinned in shipped code")
    if bad:
        print("the packaged tree does not match the contract; do not trust it")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
